"""
Part 3 enhancement: evaluation & training pipeline.

Task: given a patent's ABSTRACT as a stand-in "query", can the model retrieve that same patent's
CLAIMS text as the top match, out of a corpus of other patents' claims? Abstract and claims are
two genuinely different articulations of the same invention (different vocabulary, different
level of detail) written by the same applicant about the same patent — a natural, already-labeled
positive pair with no manual annotation needed, and (deliberately) not verbatim-overlapping the
way title/abstract/claims all being embedded together in index.py's `searchable_text` would be.

Positive pairs: (patent.abstract, patent.claims_text) for the SAME patent — close by construction.
Negative pairs: implicit, not hand-built — MultipleNegativesRankingLoss (used below) treats every
OTHER item in a training batch as a negative for a given anchor, which is exactly what the brief
notes: positive examples are far easier to generate than negative ones, and a loss that only
needs positives is a legitimate way to avoid hand-constructing negatives for this task.

Pipeline:
  1. Split the 640 patents into train/eval (80/20, deterministic).
  2. Evaluate the OFF-THE-SHELF model: Recall@1/5/10 and MRR for retrieving each eval patent's
     claims from its abstract, among the eval set's claims only (a held-out corpus).
  3. Fine-tune a fresh copy of the same base model on the TRAIN split's (abstract, claims) pairs
     using MultipleNegativesRankingLoss.
  4. Re-run the same evaluation with the fine-tuned model. Report before/after.

Per the brief: no expectation of a big improvement from ~1hr of work on 640 patents — the
deliverable is the pipeline itself and honest before/after numbers, not a claimed win.

Results are written directly into README.md (between the EVAL_RESULTS markers, in the Part 3
"evaluation & fine-tuning pipeline" section) rather than a separate file, same reasoning as
benchmark_hybrid.py: the README is the single reviewer-facing source of truth, and only the
metrics table actually changes run to run — the methodology/caveats around it are static prose
maintained directly in the README.

Run: python eval.py   (from src/, with the Part 1 venv active)
"""

from __future__ import annotations

import os
import time

import numpy as np
import torch
from sentence_transformers import InputExample, SentenceTransformer, losses
from torch.utils.data import DataLoader

from index import DEFAULT_MODEL
from ingest import load_patents

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README_PATH = os.path.join(REPO_ROOT, "README.md")
START_MARKER = "<!-- EVAL_RESULTS:START (generated by `python src/eval.py` — do not edit by hand) -->"
END_MARKER = "<!-- EVAL_RESULTS:END -->"

EVAL_FRACTION = 0.2  # every 5th patent goes to eval, deterministic
BATCH_SIZE = 16
EPOCHS = 2
RECALL_KS = (1, 5, 10)


# Deterministically split `patents` 80/20: every 5th patent (by list position) goes to
# eval, the rest to train.
def train_eval_split(patents):
    train, eval_ = [], []
    for i, p in enumerate(patents):
        (eval_ if i % 5 == 0 else train).append(p)
    return train, eval_


# Recall@k and MRR for retrieving each patent's own claims text from its abstract, among
# the eval set's claims texts (a held-out corpus not seen during fine-tuning).
def evaluate_retrieval(model: SentenceTransformer, eval_patents: list) -> dict:
    queries = [p.abstract for p in eval_patents]
    docs = [p.claims_text for p in eval_patents]

    query_emb = model.encode(queries, convert_to_numpy=True, normalize_embeddings=True, show_progress_bar=False)
    doc_emb = model.encode(docs, convert_to_numpy=True, normalize_embeddings=True, show_progress_bar=False)

    sims = query_emb @ doc_emb.T  # (n_eval, n_eval); sims[i, i] should be highest ideally
    ranks = []
    for i in range(len(eval_patents)):
        order = np.argsort(-sims[i])
        rank = int(np.nonzero(order == i)[0][0]) + 1  # 1-indexed rank of the true match
        ranks.append(rank)
    ranks = np.array(ranks)

    metrics = {f"recall@{k}": float((ranks <= k).mean()) for k in RECALL_KS}
    metrics["mrr"] = float((1.0 / ranks).mean())
    metrics["n_eval"] = len(eval_patents)
    return metrics


# Load a fresh copy of `base_model_name` and fine-tune it on `train_patents`' (abstract,
# claims) pairs with MultipleNegativesRankingLoss (see module docstring for why no explicit
# negatives are needed). Returns the fine-tuned model; weights are not saved to disk here.
def fine_tune(base_model_name: str, train_patents: list) -> SentenceTransformer:
    model = SentenceTransformer(base_model_name, device="cpu")
    examples = [InputExample(texts=[p.abstract, p.claims_text]) for p in train_patents if p.claims_text]
    dataloader = DataLoader(examples, shuffle=True, batch_size=BATCH_SIZE)
    loss = losses.MultipleNegativesRankingLoss(model)

    print(f"Fine-tuning on {len(examples)} (abstract, claims) pairs, "
          f"{EPOCHS} epoch(s), batch size {BATCH_SIZE} ...")
    start = time.time()
    model.fit(
        train_objectives=[(dataloader, loss)],
        epochs=EPOCHS,
        warmup_steps=max(1, int(0.1 * len(dataloader) * EPOCHS)),
        show_progress_bar=False,
    )
    print(f"Fine-tuning took {time.time() - start:.1f}s")
    return model


# Run the full pipeline: load data, split, evaluate the baseline model, fine-tune a fresh
# copy, evaluate again, and write the before/after report.
def main():
    patents, stats = load_patents(os.path.join(REPO_ROOT, "patent_data_small"))
    train_patents, eval_patents = train_eval_split(patents)
    print(f"{len(patents)} patents -> {len(train_patents)} train / {len(eval_patents)} eval")

    print("\n== Baseline (off-the-shelf) ==")
    base_model = SentenceTransformer(DEFAULT_MODEL, device="cpu")
    before = evaluate_retrieval(base_model, eval_patents)
    print(before)
    del base_model  # free memory before loading a second copy to fine-tune

    print("\n== Fine-tuning ==")
    tuned_model = fine_tune(DEFAULT_MODEL, train_patents)

    print("\n== After fine-tuning ==")
    after = evaluate_retrieval(tuned_model, eval_patents)
    print(after)

    write_report(before, after)
    print(f"\nUpdated the EVAL_RESULTS section in {README_PATH}")
    print("(Fine-tuned weights are NOT saved to disk — see README.md's Part 3 section for why.)")


# Render the before/after metrics table as markdown, then splice it into README.md between the
# EVAL_RESULTS markers (replacing whatever was there before), preserving the rest of the file.
def write_report(before, after):
    lines = [
        "| metric | before fine-tuning | after fine-tuning | delta |",
        "|---|---:|---:|---:|",
    ]
    for k in list(before.keys()):
        if k == "n_eval":
            continue
        b, a = before[k], after[k]
        lines.append(f"| {k} | {b:.3f} | {a:.3f} | {a - b:+.3f} |")
    generated_block = "\n".join(lines)

    with open(README_PATH, "r") as f:
        readme = f.read()

    if START_MARKER not in readme or END_MARKER not in readme:
        raise RuntimeError(
            f"Couldn't find EVAL_RESULTS markers in {README_PATH} — "
            "they must exist already (see README.md's Part 3 section) for this script to update in place."
        )

    before_text, rest = readme.split(START_MARKER, 1)
    _, after_text = rest.split(END_MARKER, 1)
    new_readme = f"{before_text}{START_MARKER}\n{generated_block}\n{END_MARKER}{after_text}"

    with open(README_PATH, "w") as f:
        f.write(new_readme)


if __name__ == "__main__":
    main()
