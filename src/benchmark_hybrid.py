"""
Times "naive" (post-filter) vs "masked" (pre-filter) hybrid search across several filter
selectivities, and writes the results table directly into README.md (between the
BENCHMARK_RESULTS markers, in the Part 1 "Hybrid search + the efficiency finding" section) —
kept in the README rather than a separate file so the reviewer-facing document is the single
source of truth, while still being regenerated from a real run rather than hand-typed.

The analysis of WHY the numbers look the way they do lives as regular hand-written prose in
README.md right after the table, not generated by this script — unlike the table, that write-up
doesn't change based on the measured numbers (it's the same explanation regardless of the exact
timings), so there's no real benefit to generating it in code versus just writing it once.

  naive:  compute cosine similarity against the ENTIRE corpus, sort, then walk the sorted list
          discarding rows that fail the metadata filter until top_k survive. This is what you get
          if you bolt metadata filtering onto vector search as an afterthought (ORDER BY
          similarity LIMIT big_N, then filter in application code).
  masked: apply the metadata filter FIRST as a boolean mask, take only the surviving rows
          (`embeddings[mask]`), and run the similarity computation over just that subset. This is
          what PatentIndex.search() in index.py does.

IMPORTANT — this was NOT a foregone conclusion, and the first version of this script actually
falsified my own assumption: at moderate selectivity, `masked` was measurably SLOWER than
`naive`, because `embeddings[mask]` triggers a numpy fancy-indexing COPY of the surviving rows,
and that copy is itself O(N) — costing about as much as the "wasted" similarity computation the
mask was supposed to save. `naive`'s single dense `embeddings @ query` is a highly optimized BLAS
call over contiguous memory, which is hard to beat with an equal-order-cost python-level filter
step. The real crossover point depends on filter selectivity — see results below.
"""

from __future__ import annotations

import os
import time

import numpy as np

from index import build_default_index

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README_PATH = os.path.join(REPO_ROOT, "README.md")
START_MARKER = "<!-- BENCHMARK_RESULTS:START (generated by `python src/benchmark_hybrid.py` — do not edit by hand) -->"
END_MARKER = "<!-- BENCHMARK_RESULTS:END -->"

N_TRIALS = 10
SCALE_FACTOR = 1000  # 640 patents x1000 => 640,000 rows, large enough for stable timing
# Three real classification-prefix filters from the data, spanning a wide range of selectivity.
FILTERS = ["B60B", "B60B104", "B60G"]


# Post-filter approach: rank the ENTIRE corpus by similarity first, then keep walking down
# the ranked list discarding rows that fail `mask` until `top_k` survive.
def naive_hybrid_search(embeddings, mask, query_vec, top_k):
    sims = embeddings @ query_vec  # similarity over the FULL corpus, every call
    order = np.argsort(-sims)
    picked = []
    for i in order:
        if mask[i]:
            picked.append(i)
            if len(picked) == top_k:
                break
    return picked


# Pre-filter approach: keep only the rows `mask` allows, then rank just that subset.
def masked_hybrid_search(embeddings, mask, query_vec, top_k):
    candidate_idx = np.nonzero(mask)[0]
    sims = embeddings[candidate_idx] @ query_vec  # copies the filtered subset, then multiplies
    order = np.argsort(-sims)[:top_k]
    return candidate_idx[order]


# Call `fn(*args)` once to warm up, then time the average of `n_trials` further calls.
def time_fn(fn, *args, n_trials=N_TRIALS):
    fn(*args)  # warm up
    start = time.perf_counter()
    for _ in range(n_trials):
        fn(*args)
    return (time.perf_counter() - start) / n_trials


# Build the index, then for each filter in FILTERS time naive vs masked search on a
# synthetically scaled-up copy of the corpus, printing and writing the results table.
def main():
    idx = build_default_index()
    query_vec = idx.model.encode(
        ["suspension damping system for a wheel"], convert_to_numpy=True, normalize_embeddings=True
    )[0]

    embeddings = np.tile(idx.embeddings, (SCALE_FACTOR, 1))
    n = embeddings.shape[0]
    print(f"Base corpus: {len(idx.patents)} patents, scaled x{SCALE_FACTOR} -> {n:,} rows")

    rows = []
    for prefix in FILTERS:
        base_mask = idx.metadata_mask(classification_prefix=prefix)
        mask = np.tile(base_mask, SCALE_FACTOR)
        selectivity = mask.mean()

        naive_time = time_fn(naive_hybrid_search, embeddings, mask, query_vec, 10)
        masked_time = time_fn(masked_hybrid_search, embeddings, mask, query_vec, 10)
        speedup = naive_time / masked_time if masked_time > 0 else float("inf")

        rows.append((prefix, selectivity, naive_time * 1000, masked_time * 1000, speedup))
        print(f"{prefix:10s} selectivity={selectivity:7.2%}  naive={naive_time*1000:8.2f}ms  "
              f"masked={masked_time*1000:8.2f}ms  speedup={speedup:6.2f}x")

    write_report(rows)
    print(f"\nUpdated the BENCHMARK_RESULTS section in {README_PATH}")


# Render the timing table as markdown, then splice it into README.md between the
# BENCHMARK_RESULTS markers (replacing whatever was there before), preserving the rest of the file.
def write_report(rows):
    lines = [
        "| filter | selectivity | naive (ms) | masked (ms) | speedup |",
        "|---|---:|---:|---:|---:|",
    ]
    for prefix, sel, naive_ms, masked_ms, speedup in rows:
        lines.append(f"| `{prefix}` | {sel:.2%} | {naive_ms:.2f} | {masked_ms:.2f} | {speedup:.2f}x |")
    generated_block = "\n".join(lines)

    with open(README_PATH, "r") as f:
        readme = f.read()

    if START_MARKER not in readme or END_MARKER not in readme:
        raise RuntimeError(
            f"Couldn't find BENCHMARK_RESULTS markers in {README_PATH} — "
            "they must exist already (see README.md's Part 1 section) for this script to update in place."
        )

    before, rest = readme.split(START_MARKER, 1)
    _, after = rest.split(END_MARKER, 1)
    new_readme = f"{before}{START_MARKER}\n{generated_block}\n{END_MARKER}{after}"

    with open(README_PATH, "w") as f:
        f.write(new_readme)


if __name__ == "__main__":
    main()
